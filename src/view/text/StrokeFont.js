/**
 * Elliptical arc as a flat [x0,y0,x1,y1,...] polyline.
 * Angles in degrees; direction follows the sign of (a1 - a0).
 */
function arc(cx, cy, rx, ry, a0, a1, n = 8) {
  const out = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    out.push(cx + rx * Math.cos(a), cy + ry * Math.sin(a));
  }
  return out;
}

const circle = (cx, cy, rx, ry, n = 12) => arc(cx, cy, rx, ry, 0, 360, n);

