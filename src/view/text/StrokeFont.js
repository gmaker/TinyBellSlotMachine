export const StrokeFont = Object.freeze({
  /** Glyph box width relative to size (cap height). */
  aspect: 0.66,
  /** Extra tracking between glyphs relative to size. */
  tracking: 0.2,
  /** Space width relative to size. */
  space: 0.45,
  /** Default stroke half-width relative to size. */
  strokeWidth: 0.075,

  /**
   * @param {string} char
   * @returns {number[][]|null} polylines in unit space, or null for whitespace
   */
  glyph(char) {
    if (char === ' ' || char === ' ') return null;
    const upper = char.toUpperCase();
    return GLYPHS[upper] ?? GLYPHS[char] ?? FALLBACK;
  },

  /**
   * Horizontal advance factor (1 = normal).
   * @param {string} char
   */
  advance(char) {
    const upper = char.toUpperCase();
    return NARROW[upper] ?? WIDE[upper] ?? 1;
  },
});

const FALLBACK = [[0.15, 0, 0.15, 1, 0.85, 1, 0.85, 0, 0.15, 0]];
